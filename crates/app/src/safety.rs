//! 安全模式（`--safe-mode`）：一个开关，把「脚本」和「外部主题」全部退回随包
//! 内置的那一份。
//!
//! 为什么要有它：一个包能改一切 —— 启动时建窗格、改工具栏、换配色，画错了就是
//! 一个看不清也点不动的窗口。真到这个地步，用户面前是一个「不知道是谁干的、
//! 也不知道怎么退出去」的编辑器，而本来唯一的出路是手工删目录或改
//! `setting.ini`。这个开关就是那条不用懂文件结构的出路。
//!
//! 关掉三样：
//!
//! 1. **脚本**（包和散装都算）—— 宿主照样建，只是命令表空着，各处的判空逻辑
//!    不用为此改一遍；
//! 2. **外部主题覆盖**（`themes/<name>.ini`）—— 只认随包内置的那份，名字不
//!    认识就退回默认那套（见 [`crate::themes::bundled_or_default`]）；
//! 3. **两条热重载轮询**（脚本的、主题的）—— 否则文件一动，刚关掉的东西就自己
//!    回来了。
//!
//! 它**不写任何东西**：不停用任何包、不改 `setting.ini`、不删文件。去掉开关再
//! 启动，一切照旧 —— 这正是它和「在管理器里停用」的分工：那个是决定，这个是
//! 临时进来一趟。
//!
//! 验证方式是整帧比：装着一个包、放着一份外部主题，`--safe-mode` 启动的那一帧
//! 要和「从没装过」逐像素相同。

use std::sync::atomic::{AtomicBool, Ordering};

/// 进程级的一个位。只有启动时写一次（`main` 认命令行），之后全是读 ——
/// `Relaxed` 就够：没有任何一处需要它和别的内存操作排先后。
static ON: AtomicBool = AtomicBool::new(false);

pub fn on() -> bool {
    ON.load(Ordering::Relaxed)
}

/// 只由 `main` 在开窗之前调。别在运行期翻它：装载是启动那一刻做的，
/// 中途翻过来只会得到「一半东西没装」的窗口。
pub fn set(value: bool) {
    ON.store(value, Ordering::Relaxed);
}

