/// The 命令 and 说明 for one id, or two empty strings when the id has no row.
/// The list walks the table itself, so only an id-first caller needs this.
#[allow(dead_code)]
pub(super) fn text_for(id: u32) -> (&'static str, &'static str) {
    match CMD_TEXT.binary_search_by_key(&id, |row| row.0) {
        Ok(i) => (CMD_TEXT[i].1, CMD_TEXT[i].2),
        Err(_) => ("", ""),
    }
}
